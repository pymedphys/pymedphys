def _segment(code, payload):
    return struct.pack(">BBH", 0xFF, code, len(payload) + 2) + payload


@st.composite
def _structures(draw):
    """A codestream of one tile-part whose SIZ, COD, and QCD are drawn, with a
    body of random bytes, so that the geometry of tiles, resolutions,
    precincts, and code-blocks is drawn too."""
    sides = st.one_of(
        st.integers(1, 64), st.integers(1, 0xFFFF), st.sampled_from([4096, 0xFFFF])
    )
    columns, rows = draw(sides), draw(sides)
    tile = draw(st.sampled_from([0, 1 << 15, 1 << 10, 64]))
    tile_columns, tile_rows = (columns, rows) if not tile else (tile, tile)
    components = draw(st.integers(1, 3))
    levels = draw(st.integers(0, 8))
    scod = draw(st.integers(0, 7))
    precincts = bytes(
        draw(st.lists(st.integers(0, 255), min_size=levels + 1, max_size=levels + 1))
    )
    cod = struct.pack(
        ">BBHB", scod, draw(st.integers(0, 4)), draw(st.integers(1, 64)), 0
    )
    cod += bytes(
        [
            levels,
            draw(st.integers(0, 8)),
            draw(st.integers(0, 8)),
            draw(st.sampled_from([0, 0x01, 0x04, 0x40])),
            1,
        ]
    )
    cod += precincts if scod & 1 else b""
    qcd = bytes([2 << 5]) + bytes([8 << 3] * (3 * levels + 1))
    body = draw(st.binary(max_size=256))
    tile_part = struct.pack(">HIBB", 0, 12 + 2 + len(body), 0, 1)
    size = struct.pack(
        ">H8IH", 0, columns, rows, 0, 0, tile_columns, tile_rows, 0, 0, components
    )
    return b"".join(
        [
            b"\xff\x4f",
            _segment(0x51, size + bytes([11, 1, 1]) * components),
            _segment(0x52, cod),
            _segment(0x5C, qcd),
            _segment(0x90, tile_part),
            b"\xff\x93",
            body,
            b"\xff\xd9",
        ]
    )


