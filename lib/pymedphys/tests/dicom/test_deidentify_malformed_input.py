@functools.lru_cache(maxsize=None)
def _transform():
    return InstanceTransform(compose_policy("basic"), KEY, unvalidated_policy=True)


def _decodable_images():
    """The images whose Pixel Data is native or can be decoded here."""
    return tuple(
        data
        for syntax, data in _images()
        if syntax not in pixel_decoding.DECODING_PLUGINS
        or pixel_decoding.decoder_available(syntax)
    )


@st.composite
def _planted(draw):
    """A mutated image, with one of the name's forms written over some of its
    bytes, between NULs, so that no rule of the search for text, such as one
    that a letter beside a name makes it part of a longer word, excuses it."""
    data = bytearray(draw(mutated(_decodable_images(), near=b"\xff")))
    needle = b"\x00" + draw(st.sampled_from(NEEDLES)) + b"\x00"
    at = draw(st.integers(0, max(len(data) - len(needle), 0)))
    data[at : at + len(needle)] = needle
    return bytes(data)


def _collected_name(evidence):
    coverage = evidence.coverage if hasattr(evidence, "coverage") else evidence
    if not isinstance(coverage, Coverage):
        return False
    return any(
        str(value.source) == "(0010,0010)" and str(value.value) == NAME
        for value in coverage.collected
    )


# A fifth of the profile's examples, since each runs a whole instance.
@hypothesis.settings(SETTINGS, max_examples=max(SETTINGS.max_examples // 5, 20))
@hypothesis.given(st.one_of(_planted(), mutated(_decodable_images(), near=b"\xff")))
def test_an_image_is_transformed_or_withheld_and_a_release_holds_no_name(data):
    try:
        record = InstanceRecord.from_file(data)
    # The run refuses or sequesters a file whose record cannot be read.
    except Exception:  # pylint: disable = broad-exception-caught
        return
    result = _transform()(data, record)
    assert isinstance(result, (Transformed, Sequestered))
    if not isinstance(result, Transformed):
        return
    verdict = ReleaseGate()(result.data, result.evidence, (result.evidence,))
    if isinstance(verdict, Release) and _collected_name(result.evidence):
        written = result.data.upper()
        assert not any(needle in written for needle in NEEDLES)
