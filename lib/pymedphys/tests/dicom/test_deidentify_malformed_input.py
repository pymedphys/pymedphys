def _check_ranges(ranges, data):
    assert ranges == sorted(ranges)
    for start, stop in ranges:
        assert 0 <= start <= stop <= len(data)
    for (_, stop), (start, _) in zip(ranges, ranges[1:]):
        assert stop <= start


def _jpeg_scan_bytes_are_data(syntax, data, ranges):
    """Return whether each 0xFF in the ranges, and any fill bytes after it,
    is followed by a stuffed byte or a restart marker, so that no marker
    segment, which could hold text, is taken as entropy-coded data."""
    ls = syntax in codestreams._JPEG_LS  # pylint: disable = protected-access
    for start, stop in ranges:
        position = data.find(b"\xff", start, stop)
        while position >= 0:
            following = position + 1
            while following < stop and data[following] == 0xFF:
                following += 1
            if following == stop:
                return False
            byte = data[following]
            stuffed = following == position + 1 and (byte < 0x80 if ls else byte == 0)
            if not (stuffed or 0xD0 <= byte <= 0xD7):
                return False
            position = data.find(b"\xff", following + 1, stop)
    return True


@SETTINGS
@hypothesis.given(st.sampled_from(ENCAPSULATED), st.data())
def test_entropy_coded_data_are_found_in_any_codestreams_or_none(syntax, data):
    joined = data.draw(
        st.one_of(
            mutated(_all_codestreams(), near=b"\xff"),
            st.lists(mutated(_all_codestreams(), near=b"\xff"), max_size=3).map(
                b"".join
            ),
        )
    )
    ranges = codestreams.entropy_coded(syntax, joined)
    if ranges is None:
        return
    _check_ranges(ranges, joined)
    if syntax not in codestreams._JPEG_2000:  # pylint: disable = protected-access
        assert _jpeg_scan_bytes_are_data(syntax, joined, ranges)


@SETTINGS
@hypothesis.given(st.sampled_from(ENCAPSULATED), st.data())
def test_any_codestream_is_cut_or_refused_and_a_cut_leaves_nothing_to_cut(syntax, data):
    frame = data.draw(mutated(_all_codestreams(), near=b"\xff"))
    try:
        cut = codestreams.cut_codestream(syntax, frame)
    except CodestreamRefused as refused:
        assert refused.reason in (
            TransformReason.UNPARSABLE_CODESTREAM,
            TransformReason.UNCUTTABLE_METADATA,
        )
        return
    if cut is None:
        return
    assert len(cut) < len(frame)
    assert codestreams.cut_codestream(syntax, cut) is None
    assert codestreams.entropy_coded(syntax, cut) is not None


