@functools.lru_cache(maxsize=None)
def _frame():
    return (np.arange(32 * 32, dtype=np.uint16).reshape(32, 32) * 37) % 4096


@functools.lru_cache(maxsize=None)
def _images():
    """CT images, as ``(syntax, file)``, in each syntax that the tests here
    can encode, with a comment and an application segment in each JPEG
    codestream and a comment in each JPEG 2000 one, and with several frames
    found by a Basic Offset Table, by an Extended Offset Table, and by
    parsing the fragments."""
    frame = _frame()
    jpeg = compressed._with_jpeg_text(  # pylint: disable = protected-access
        compressed.jpeg_lossless(frame, precision=12), "SYNMK"
    )
    three = [jpeg] * 3
    starts = compressed.frame_starts(three)
    lengths = [len(c) + len(c) % 2 for c in three]
    image = functools.partial(
        compressed.ct_image, rows=32, columns=32, bits=12, name=NAME
    )
    sv1 = compressed.JPEG_LOSSLESS_SV1
    images = [
        (EXPLICIT, synthetic.written(_ct(frame))),
        (compressed.RLE_LOSSLESS, compressed.rle_ct_image(frame, name=NAME)),
        (sv1, image(sv1, [jpeg])),
        (sv1, image(sv1, three, number_of_frames=3, offsets=starts)),
        (sv1, image(sv1, three, number_of_frames=3, extended=(starts, lengths))),
        (sv1, image(sv1, [b"".join(three)], number_of_frames=3)),
    ]
    for syntax, codestream in _jpeg_2000_codestreams().items():
        images.append((syntax, image(syntax, [codestream])))
    return tuple(images)


@functools.lru_cache(maxsize=None)
def _jpeg_2000_codestreams():
    """pylibjpeg-openjpeg's codestreams, lossless and lossy, keyed by syntax,
    or none where it is not installed."""
    try:
        import openjpeg  # pylint: disable = import-outside-toplevel, import-error, unused-import
    except ImportError:
        return {}
    frame = _frame()
    return {
        J2K_LOSSLESS: compressed.jpeg_2000(frame, precision=12),
        J2K: compressed.jpeg_2000(frame, precision=12, compression_ratios=[20, 5, 1]),
    }


@functools.lru_cache(maxsize=None)
def _codestreams():
    """JPEG and JPEG 2000 codestreams, keyed by an encapsulating syntax."""
    lossless = compressed.jpeg_lossless(_frame(), precision=12)
    found = {
        compressed.JPEG_LOSSLESS_SV1: [
            lossless,
            compressed._with_jpeg_text(lossless, "SYNMK"),  # pylint: disable = protected-access
        ],
        compressed.JPEG_EXTENDED: [compressed.jpeg_extended_mid_grey(8, 8)],
        J2K_LOSSLESS: list(_packet_codestreams()),
    }
    for syntax, codestream in _jpeg_2000_codestreams().items():
        found.setdefault(syntax, []).append(codestream)
    return {syntax: tuple(each) for syntax, each in found.items()}


@functools.lru_cache(maxsize=None)
def _packet_codestreams():
    """Codestreams whose packet headers the synthetic writer gives: Part 1
    and HT code-blocks, several layers, SOP and EPH markers, and the
    code-block styles that change how codeword segments are counted."""
    contribution, write = synthetic_j2k.contribution, synthetic_j2k.codestream
    planes = synthetic_j2k.MAGNITUDE_BIT_PLANES
    full = 3 * planes - 2
    four = [contribution((full, 5))] * 4
    return (
        write([four], [0, 0, 0, 0], size=(16, 16)),
        write(
            [[contribution((10, 3))] * 4, [contribution((full - 10, 4))] * 4],
            [0, 0, 0, 0],
            size=(16, 16),
            scod=synthetic_j2k.SOP | synthetic_j2k.EPH,
        ),
        write(
            [[contribution((10, 50), (2, 3), (1, 4), (2, 5), (1, 6), (2, 7), (1, 8))]],
            [2],
            style=synthetic_j2k.BYPASS,
        ),
        write(
            [[contribution(*[(1, 3)] * (3 * (planes - 2) - 2))]],
            [2],
            style=synthetic_j2k.TERMINATE_ALL,
        ),
        write([[contribution((1, 30), (2, 4))]], [planes - 2], style=synthetic_j2k.HT),
    )


def _all_codestreams():
    return tuple(c for each in _codestreams().values() for c in each)


def _check_layout(layout, data):
    """Check that the layout accounts for every byte of ``data`` once, and
    that each element it read is where its spans are."""
    assert layout.size == len(data)
    spans = layout.spans
    if not data:
        assert spans == ()
        return
    assert spans[0].start == 0
    assert spans[-1].end == len(data)
    for before, after in zip(spans, spans[1:]):
        assert before.end == after.start
    for span in spans:
        assert span.start < span.end
        if span.value_start is not None:
            assert span.start <= span.value_start <= span.end
    if layout.readable:
        assert Region.TRAILING not in {span.location.region for span in spans}
    starts = [span.start for span in spans]
    for extent in layout.elements:
        assert 0 <= extent.start <= extent.value_start <= extent.end <= len(data)
        path = extent.location.element
        inside = spans[starts.index(extent.start) :]
        for span in inside:
            if span.start >= extent.end:
                break
            element = span.location.element
            # Each span of an element is the element's own, or of one in
            # its items.
            assert element == path or (
                element.items[: len(path.items)] == path.items
                and len(element.items) > len(path.items)
                and element.items[len(path.items)][0] == path.tag
            )
    for offset in sorted({0, len(data) // 2, len(data) - 1}):
        span = next(s for s in spans if s.start <= offset < s.end)
        assert layout.locate(offset) == span.location


