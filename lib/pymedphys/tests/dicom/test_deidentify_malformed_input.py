"""Malformed input to the parsers of untrusted bytes, generated by Hypothesis.

The file reader (:mod:`.file_layout`), the codestream parsers
(:mod:`.codestreams` and :mod:`.frame_headers`), and the JPEG 2000 packet
reader (:mod:`.jpeg_2000_packets`) read bytes that anyone can write. Each
test here mutates synthetic files and codestreams, or writes structures
from random parameters, and requires that the parser either reads them or
refuses them as it documents: it never raises anything else, never takes
time out of proportion to the input, and accounts for every byte, so that
the residual search is never pointed past one. The last test runs whole
instances through the transform and the release gate, and requires that a
released file never holds the source's name, planted anywhere in it.

CI runs Hypothesis's default number of examples. A longer campaign runs the
same tests with the ``deid-fuzz`` profile of the root conftest::

    pymedphys dev tests tests/dicom/test_deidentify_malformed_input.py \\
        --hypothesis-profile=deid-fuzz --hypothesis-seed=1
"""

