@st.composite
def mutated(draw, seeds, near=b""):
    """Draw a seed, then change it a few times: flip, set, insert, delete, or
    duplicate bytes, write an interesting integer, or truncate it.

    Half the changes are made just after an occurrence of ``near``, such as
    0xFF before a marker, so that headers are changed more often than the
    bulk data between them.
    """
    data = bytearray(draw(st.sampled_from(seeds)))
    marks = [i for i in range(len(data)) if near and data.startswith(near, i)]
    for _ in range(draw(st.integers(1, 6))):
        if marks and draw(st.booleans()):
            mark = draw(st.sampled_from(marks))
            at = min(mark + draw(st.integers(0, 8)), len(data))
        else:
            at = draw(st.integers(0, len(data)))
        change = draw(
            st.sampled_from(
                ["flip", "set", "insert", "delete", "duplicate", "integer", "truncate"]
            )
        )
        if change == "flip" and at < len(data):
            data[at] ^= 1 << draw(st.integers(0, 7))
        elif change == "set" and at < len(data):
            data[at] = draw(st.integers(0, 255))
        elif change == "insert":
            data[at:at] = draw(st.binary(min_size=1, max_size=16))
        elif change == "delete":
            del data[at : at + draw(st.integers(1, 16))]
        elif change == "duplicate":
            data[at:at] = data[at : at + draw(st.integers(1, 64))]
        elif change == "integer":
            form = draw(st.sampled_from(["<H", "<I", ">H", ">I"]))
            value = draw(st.sampled_from(INTERESTING)) % (
                1 << 8 * struct.calcsize(form)
            )
            data[at : at + struct.calcsize(form)] = struct.pack(form, value)
        elif change == "truncate":
            del data[at:]
    return bytes(data)


def _ct(frame=None):
    """A CT slice of ``NAME``, with ``frame`` as native Pixel Data."""
    dataset = synthetic.ct_slice(0)
    dataset.PatientName = NAME
    if frame is not None:
        dataset.SamplesPerPixel = 1
        dataset.PhotometricInterpretation = "MONOCHROME2"
        dataset.Rows, dataset.Columns = frame.shape
        dataset.BitsAllocated, dataset.BitsStored, dataset.HighBit = 16, 12, 11
        dataset.PixelRepresentation = 0
        dataset.PixelData = frame.astype("<u2").tobytes()
    return dataset


