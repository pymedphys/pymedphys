"""Common personal names, which the vocabulary of technique descriptors excludes.

The list is generated by :mod:`pymedphys._dev.deid_common_names` from the
United States Census Bureau's 1990 census name files, which are in the public
domain: every given name of its first-name files, and every surname held by
at least 0.001 percent of the population. A word of the list is kept
automatically in a descriptor only where a reviewer has made it an exception
with a recorded basis, such as ``HEAD``, which is both a body part and a
surname.
"""

from __future__ import annotations

import functools
import hashlib
import json
import pathlib
import re
from collections.abc import Sequence

SCHEMA = "pymedphys-deid-common-names/1"
COMMON_NAMES_FILE = pathlib.Path(__file__).with_name("common_names.json")
_NAME = re.compile(r"[A-Z]+")


class CommonNamesFileError(ValueError):
    """The common names file is not the generated list."""


def names_sha256(names: Sequence[str]) -> str:
    """Return the SHA-256 of the names, one per line, each ended by a line feed."""
    return hashlib.sha256("".join(f"{name}\n" for name in names).encode()).hexdigest()


@functools.lru_cache(maxsize=None)
def load_common_names(path: pathlib.Path = COMMON_NAMES_FILE) -> frozenset[str]:
    """Return the common names, in capitals.

    Raises
    ------
    CommonNamesFileError
        If the file is not a :data:`SCHEMA` file, a name is not a word of
        capital letters, the names are not sorted and distinct, or they do
        not have the digest the file records.
    """
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise CommonNamesFileError("the common names file cannot be read") from error
    names = document.get("names") if isinstance(document, dict) else None
    if (
        document.get("schema") != SCHEMA
        or not isinstance(names, list)
        or not all(isinstance(n, str) and _NAME.fullmatch(n) for n in names)
    ):
        raise CommonNamesFileError(f"the file is not a {SCHEMA} file")
    if names != sorted(set(names)):
        raise CommonNamesFileError("the common names are not sorted and distinct")
    if names_sha256(names) != document.get("names_sha256"):
        raise CommonNamesFileError("the common names do not match their digest")
    return frozenset(names)
